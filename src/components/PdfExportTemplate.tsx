import React from 'react';
import { ReconciliationResponse } from '../types';
import { getDebitCredit, getDynamicLabel } from '../services/reconciliation';
import { CheckCircle, AlertCircle, PlusCircle, MinusCircle, Activity } from 'lucide-react';

interface PdfExportTemplateProps {
  results: ReconciliationResponse;
  reportId: string;
  username: string;
}

export const PdfExportTemplate = React.forwardRef<HTMLDivElement, PdfExportTemplateProps>(
  ({ results, reportId, username }, ref) => {
    const formatCurrency = (amount: number) => {
      return amount.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
    };

    if (!results.bankReconciliation) return null;

    return (
      <div ref={ref} className="bg-white p-10 w-[1000px] text-slate-800 font-sans mx-auto">
        {/* Header */}
        <div className="flex justify-between items-start border-b-2 border-slate-200 pb-6 mb-8">
          <div>
            <h1 className="text-3xl font-bold text-slate-900 mb-2">Reconciliation Report</h1>
            <p className="text-sm text-slate-500">Report ID: {reportId}</p>
          </div>
          <div className="text-right flex flex-col items-end">
            <div className="flex items-center space-x-2 mb-2">
              <div className="bg-indigo-600 p-1.5 rounded-lg">
                <Activity className="w-5 h-5 text-white" />
              </div>
              <span className="text-xl font-bold text-slate-900">ReconMatch</span>
            </div>
            <p className="text-sm text-slate-600">Date: {new Date().toLocaleDateString()}</p>
            <p className="text-sm text-slate-600">Generated by: {username}</p>
          </div>
        </div>

        {/* Summary Details */}
        <div className="space-y-6 mb-12">
          <h2 className="text-2xl font-bold text-slate-800 border-b border-slate-200 pb-2">Bank Reconciliation Summary</h2>
          
          {/* Opening Balance */}
          <div className="flex justify-between items-center py-3 border-b border-slate-100">
            <span className="text-lg font-medium text-slate-700">Opening Balance (Sheet 1)</span>
            <span className="text-lg font-bold text-slate-900">{formatCurrency(results.bankReconciliation.openingBalance)}</span>
          </div>

          {/* Additions */}
          <div>
            <div className="flex justify-between items-center py-2">
              <span className="text-md font-bold text-emerald-700 flex items-center">
                <PlusCircle className="w-5 h-5 mr-2" /> Additions (Sheet 2 Unmatched)
              </span>
              <span className="text-md font-bold text-emerald-700">{formatCurrency(results.bankReconciliation.totalAdditions)}</span>
            </div>
            <div className="pl-7 space-y-1 mt-2">
              {results.unmatchedB.map((record, idx) => {
                const { debit, credit } = getDebitCredit(record, results.mappingsB);
                return (
                  <div key={`b-${idx}`} className="flex justify-between text-sm text-slate-600 border-b border-slate-50 pb-1">
                    <span className="truncate pr-4">{getDynamicLabel(record, results.mappingsB)}</span>
                    <span>{formatCurrency(debit + credit)}</span>
                  </div>
                );
              })}
              {results.adjustments.filter(a => !a.approved).map((adj, idx) => (
                <div key={`adj-b-${idx}`} className="flex justify-between text-sm text-slate-600 border-b border-slate-50 pb-1">
                  <span className="truncate pr-4">{adj.identifier} <span className="text-rose-500 text-xs">(Rejected Adj)</span></span>
                  <span>{formatCurrency(adj.amountB)}</span>
                </div>
              ))}
              {results.unmatchedB.length === 0 && results.adjustments.filter(a => !a.approved).length === 0 && (
                <div className="text-sm text-slate-400 italic">No additions</div>
              )}
            </div>
          </div>

          {/* Deductions */}
          <div>
            <div className="flex justify-between items-center py-2">
              <span className="text-md font-bold text-rose-700 flex items-center">
                <MinusCircle className="w-5 h-5 mr-2" /> Deductions (Sheet 1 Unmatched)
              </span>
              <span className="text-md font-bold text-rose-700">{formatCurrency(results.bankReconciliation.totalDeductions)}</span>
            </div>
            <div className="pl-7 space-y-1 mt-2">
              {results.unmatchedA.map((record, idx) => {
                const { debit, credit } = getDebitCredit(record, results.mappingsA);
                return (
                  <div key={`a-${idx}`} className="flex justify-between text-sm text-slate-600 border-b border-slate-50 pb-1">
                    <span className="truncate pr-4">{getDynamicLabel(record, results.mappingsA)}</span>
                    <span>{formatCurrency(debit + credit)}</span>
                  </div>
                );
              })}
              {results.adjustments.filter(a => !a.approved).map((adj, idx) => (
                <div key={`adj-a-${idx}`} className="flex justify-between text-sm text-slate-600 border-b border-slate-50 pb-1">
                  <span className="truncate pr-4">{adj.identifier} <span className="text-rose-500 text-xs">(Rejected Adj)</span></span>
                  <span>{formatCurrency(adj.amountA)}</span>
                </div>
              ))}
              {results.unmatchedA.length === 0 && results.adjustments.filter(a => !a.approved).length === 0 && (
                <div className="text-sm text-slate-400 italic">No deductions</div>
              )}
            </div>
          </div>

          {/* Adjustments */}
          {results.adjustments && results.adjustments.length > 0 && (
            <div>
              <div className="flex justify-between items-center py-2">
                <span className="text-md font-bold text-amber-700 flex items-center">
                  <AlertCircle className="w-5 h-5 mr-2" /> Adjustments (Amount Differences)
                </span>
                <span className="text-md font-bold text-amber-700">{formatCurrency(results.bankReconciliation.netAdjustments)}</span>
              </div>
              <div className="pl-7 space-y-2 mt-2">
                {results.adjustments.map((adj) => (
                  <div key={adj.id} className={`flex items-center justify-between text-sm border-b border-slate-50 pb-2 ${!adj.approved ? 'opacity-50' : ''}`}>
                    <div className="flex-1">
                      <div className="font-medium text-slate-700">{adj.identifier}</div>
                      <div className="text-xs text-slate-500 flex space-x-4 mt-1">
                        <span>Sheet 1: {formatCurrency(adj.amountA)}</span>
                        <span>Sheet 2: {formatCurrency(adj.amountB)}</span>
                      </div>
                    </div>
                    <div className="flex items-center space-x-4">
                      <div className={`font-medium ${adj.difference > 0 ? 'text-emerald-600' : 'text-rose-600'}`}>
                        {adj.difference > 0 ? '+' : ''}{formatCurrency(adj.difference)}
                      </div>
                      <div className={`px-2 py-0.5 rounded text-xs font-medium ${adj.approved ? 'bg-emerald-100 text-emerald-700' : 'bg-slate-100 text-slate-600'}`}>
                        {adj.approved ? 'Approved' : 'Rejected'}
                      </div>
                    </div>
                  </div>
                ))}
              </div>
            </div>
          )}

          {/* Adjusted Balance */}
          <div className="flex justify-between items-center py-3 border-t-2 border-slate-200 mt-4 break-inside-avoid">
            <span className="text-lg font-bold text-slate-800">Adjusted Balance</span>
            <span className="text-lg font-bold text-slate-900">{formatCurrency(results.bankReconciliation.adjustedBalance)}</span>
          </div>

          {/* Target Balance */}
          <div className="flex justify-between items-center py-3 border-b border-slate-100 break-inside-avoid">
            <span className="text-lg font-medium text-slate-700">Target Balance (Sheet 2)</span>
            <span className="text-lg font-bold text-slate-900">{formatCurrency(results.bankReconciliation.targetBalance)}</span>
          </div>

          {/* Difference & Status */}
          <div className={`flex justify-between items-center py-4 px-4 rounded-xl mt-6 break-inside-avoid ${results.bankReconciliation.isBalanced ? 'bg-emerald-50 border border-emerald-200' : 'bg-rose-50 border border-rose-200'}`}>
            <div className="flex items-center space-x-3">
              {results.bankReconciliation.isBalanced ? <CheckCircle className="w-6 h-6 text-emerald-600" /> : <AlertCircle className="w-6 h-6 text-rose-600" />}
              <span className={`text-lg font-bold ${results.bankReconciliation.isBalanced ? 'text-emerald-800' : 'text-rose-800'}`}>
                {results.bankReconciliation.isBalanced ? 'Balanced' : 'Difference'}
              </span>
            </div>
            <span className={`text-xl font-bold ${results.bankReconciliation.isBalanced ? 'text-emerald-700' : 'text-rose-700'}`}>
              {formatCurrency(results.bankReconciliation.difference)}
            </span>
          </div>
        </div>

        {/* Matches Table */}
        <div className="mt-12" style={{ pageBreakBefore: 'always' }}>
          <h2 className="text-2xl font-bold text-slate-800 border-b border-slate-200 pb-2 mb-4">Matched Records</h2>
          <table className="w-full text-left border-collapse text-sm">
            <thead>
              <tr className="bg-slate-100 border-b border-slate-300">
                <th className="p-3 font-semibold text-slate-700">Type</th>
                <th className="p-3 font-semibold text-slate-700">Dataset A</th>
                <th className="p-3 font-semibold text-slate-700">Dataset B</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Total Match</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Diff</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200">
              {results.matches.map((match, idx) => (
                <tr key={idx} className="break-inside-avoid">
                  <td className="p-3 align-top">
                    <span className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-medium capitalize
                      ${match.type === 'exact' ? 'bg-emerald-100 text-emerald-800' : 
                        match.type === 'combined' ? 'bg-blue-100 text-blue-800' : 
                        match.type === 'manual' ? 'bg-purple-100 text-purple-800' :
                        'bg-amber-100 text-amber-800'}`}
                    >
                      {match.type}
                    </span>
                  </td>
                  <td className="p-3 align-top text-slate-600">
                    <div className="space-y-1">
                      {match.recordsA.map((r, i) => (
                        <div key={i}>{getDynamicLabel(r, results.mappingsA)}</div>
                      ))}
                    </div>
                  </td>
                  <td className="p-3 align-top text-slate-600">
                    <div className="space-y-1">
                      {match.recordsB.map((r, i) => (
                        <div key={i}>{getDynamicLabel(r, results.mappingsB)}</div>
                      ))}
                    </div>
                  </td>
                  <td className="p-3 align-top text-right font-medium text-slate-800">
                    {formatCurrency(match.totalAmountA)}
                  </td>
                  <td className="p-3 align-top text-right">
                    <span className={`font-medium ${match.difference > 0 ? 'text-rose-600' : 'text-slate-400'}`}>
                      {formatCurrency(match.difference)}
                    </span>
                  </td>
                </tr>
              ))}
              {results.matches.length === 0 && (
                <tr>
                  <td colSpan={5} className="p-4 text-center text-slate-500">No matches found.</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        {/* Unmatched A Table */}
        <div className="mt-12" style={{ pageBreakBefore: 'always' }}>
          <h2 className="text-2xl font-bold text-slate-800 border-b border-slate-200 pb-2 mb-4">Unmatched Records (Sheet 1)</h2>
          <table className="w-full text-left border-collapse text-sm">
            <thead>
              <tr className="bg-slate-100 border-b border-slate-300">
                <th className="p-3 font-semibold text-slate-700">Record</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Debit</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Credit</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Total</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200">
              {results.unmatchedA.map((record, idx) => {
                const { debit, credit } = getDebitCredit(record, results.mappingsA);
                return (
                  <tr key={idx} className="break-inside-avoid">
                    <td className="p-3 align-top text-slate-600">
                      <div>{getDynamicLabel(record, results.mappingsA)}</div>
                    </td>
                    <td className="p-3 align-top text-right text-slate-600">
                      {debit > 0 ? formatCurrency(debit) : '-'}
                    </td>
                    <td className="p-3 align-top text-right text-slate-600">
                      {credit > 0 ? formatCurrency(credit) : '-'}
                    </td>
                    <td className="p-3 align-top text-right font-medium text-slate-800">
                      {formatCurrency(debit + credit)}
                    </td>
                  </tr>
                );
              })}
              {results.unmatchedA.length === 0 && (
                <tr>
                  <td colSpan={4} className="p-4 text-center text-slate-500">No unmatched records.</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        {/* Unmatched B Table */}
        <div className="mt-12" style={{ pageBreakBefore: 'always' }}>
          <h2 className="text-2xl font-bold text-slate-800 border-b border-slate-200 pb-2 mb-4">Unmatched Records (Sheet 2)</h2>
          <table className="w-full text-left border-collapse text-sm">
            <thead>
              <tr className="bg-slate-100 border-b border-slate-300">
                <th className="p-3 font-semibold text-slate-700">Record</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Debit</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Credit</th>
                <th className="p-3 font-semibold text-slate-700 text-right">Total</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200">
              {results.unmatchedB.map((record, idx) => {
                const { debit, credit } = getDebitCredit(record, results.mappingsB);
                return (
                  <tr key={idx} className="break-inside-avoid">
                    <td className="p-3 align-top text-slate-600">
                      <div>{getDynamicLabel(record, results.mappingsB)}</div>
                    </td>
                    <td className="p-3 align-top text-right text-slate-600">
                      {debit > 0 ? formatCurrency(debit) : '-'}
                    </td>
                    <td className="p-3 align-top text-right text-slate-600">
                      {credit > 0 ? formatCurrency(credit) : '-'}
                    </td>
                    <td className="p-3 align-top text-right font-medium text-slate-800">
                      {formatCurrency(debit + credit)}
                    </td>
                  </tr>
                );
              })}
              {results.unmatchedB.length === 0 && (
                <tr>
                  <td colSpan={4} className="p-4 text-center text-slate-500">No unmatched records.</td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

      </div>
    );
  }
);

PdfExportTemplate.displayName = 'PdfExportTemplate';
